package com.joysistvi.day3.variable;

public class Activity1_LaguyoJ {

    public static void main(String[] args) {

        boolean is_active = true;
        System.out.println(is_active);

        byte age = 33;
        System.out.println(age);

        short bankAccount = -132;
        System.out.println(bankAccount);

        int positiveIntegers = 9;
        System.out.println(positiveIntegers);

        long creditLimit = 32000L;
        System.out.println(creditLimit);

        float average = 99.999f;
        System.out.println(average);

        double netPrice = 10.999999d;
        System.out.println(netPrice);

        char middleInitial= 'P';
        System.out.println(middleInitial);

        String firstName = "James";
        String lastName = "Laguyo";

        System.out.println("Full Name:" + lastName + ", " + firstName + " " + middleInitial + ".");
    }
}
